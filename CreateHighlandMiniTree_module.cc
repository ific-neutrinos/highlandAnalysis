//*****************************************************************************
void highlandAnalysis::CreateHighlandMiniTree::TrueRecoMatching(art::Event const &evt, const recob::PFParticle* ls_part,
								const std::vector<art::Ptr<recob::Hit>>& ls_part_hits,
								AnaParticlePD* part, std::vector<AnaTrueParticleB*>& trueParticles){
//*****************************************************************************

  bool found = false;

  //get the true particle ID that generated this reco particle
  int truePartID = GetTrueParticleIDFromPFP(evt, ls_part, ls_part_hits);

  //purity and completeness of the matching, same definitions as ProtoDUNETruthUtils::GetPurity and
  //GetCompleteness (hits with any contribution of the matched particle, without eve IDs), from the
  //backtracking cache of BuildEventCaches (not in summary mode)
  if(fFillDetail){
    part->TruePur = 0;
    part->TrueEff = 0;
    auto itall = fTrueNHitsAny.find(truePartID);
    if(truePartID != -1 && !ls_part_hits.empty() && itall != fTrueNHitsAny.end() && itall->second > 0){
      int shared = 0;
      for(const art::Ptr<recob::Hit>& h : ls_part_hits){
	if(h.key() >= fHitTrackIDs.size())continue;
	const std::vector<int>& ids = fHitTrackIDs[h.key()];
	if(std::find(ids.begin(), ids.end(), truePartID) != ids.end())shared++;
      }
      part->TruePur = (double)shared / ls_part_hits.size();
      part->TrueEff = (double)shared / itall->second;
    }
  }

  //look for it in the TrueParticles vector
  for(int itrue = 0; itrue < (int)trueParticles.size(); itrue++){
    if(truePartID == trueParticles.at(itrue)->ID){
      part->TrueObject = trueParticles.at(itrue);
      found = true;
      break;
    }
  }

  //if not found among stored true particles, look for it on the pList
  //(not for cosmics with CosmicsTruthMode 0)
  if(!found && truePartID != -1 && (part->BeamOrigin || fCosmicsTruthMode > 0)){
    if(fDebug)std::cout << "     PFParticle " << ls_part->Self() << ": true particle " << truePartID << " not stored yet, adding it" << std::endl;
    const sim::ParticleList &pList = piServ->ParticleList();
    auto it = pList.find(truePartID);
    if(it != pList.end() && it->second){
      FillTruePartInfo(evt, pList, it->second, trueParticles, NULL, -999, false);
      part->TrueObject = trueParticles.back();
      found = true;
      //its ancestors, so that the analyses know where it comes from (e.g. if a K+ comes from the
      //interaction of the beam particle)
      if(fSaveTrueAncestors)AddTrueAncestors(evt, pList, static_cast<AnaTrueParticlePD*>(trueParticles.back()), trueParticles);
    }
  }
  
  if(!found && fDebug)std::cout << "     PFParticle " << ls_part->Self() << ": no matching true particle (ID " << truePartID << ")" << std::endl;
}

//*****************************************************************************
